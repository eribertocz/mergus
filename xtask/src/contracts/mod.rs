//! MG-REQ-0202: the Rust types of every contract are generated from its schema.
//!
//! `cargo xtask contracts-generate` writes the types; `cargo xtask contracts-generated`
//! fails when the files on disk differ from what the schemas generate. Each pair below is a
//! schema directory and the directory its types are generated into: the contracts of
//! `schemas/`, and the fixture contracts the tests of `mergus-contracts` compile.

mod compatibility;
mod layout;
mod model;
mod render;

use std::fs;
use std::path::{Component, Path, PathBuf};

use crate::failure::Failure;
use crate::json::Json;
use crate::workspace;
use render::Module;

pub(crate) use compatibility::incompatibilities;

/// Each schema directory and its generated directory, relative to the workspace root.
const PAIRS: [(&[&str], &[&str]); 2] = [
    (
        &["schemas"],
        &["crates", "mergus-contracts", "src", "generated"],
    ),
    (
        &["crates", "mergus-contracts", "tests", "fixtures", "schemas"],
        &[
            "crates",
            "mergus-contracts",
            "tests",
            "fixtures",
            "generated",
        ],
    ),
];

/// Writes the generated files of every pair, and removes the Rust files no schema
/// generates.
///
/// # Errors
///
/// Fails if a schema cannot be generated or a file cannot be written or removed.
pub(crate) fn generate(root: &Path) -> Result<(), Failure> {
    for (schemas, out) in pairs(root) {
        let files = expected(root, &schemas, &out)?;
        fs::create_dir_all(&out).map_err(|error| Failure::io(&out, &error))?;
        for path in stale(&out, &files)? {
            fs::remove_file(&path).map_err(|error| Failure::io(&path, &error))?;
        }
        for (path, text) in &files {
            fs::write(path, text).map_err(|error| Failure::io(path, &error))?;
        }
    }
    Ok(())
}

/// Fails when a generated file is missing, out of date or generated by no schema.
///
/// # Errors
///
/// Fails if a schema cannot be generated, a file cannot be read, or with every difference.
pub(crate) fn check(root: &Path) -> Result<(), Failure> {
    let mut problems = Vec::new();
    for (schemas, out) in pairs(root) {
        problems.extend(differences(root, &schemas, &out)?);
    }
    Failure::from_problems("contracts-generated", &problems)
}

fn pairs(root: &Path) -> Vec<(PathBuf, PathBuf)> {
    let join = |parts: &[&str]| {
        parts
            .iter()
            .fold(root.to_path_buf(), |path, part| path.join(part))
    };
    PAIRS
        .iter()
        .map(|(schemas, out)| (join(schemas), join(out)))
        .collect()
}

/// Lists how the files in `out` differ from what `schemas` generates.
///
/// # Errors
///
/// Fails if a schema cannot be generated or a file cannot be read.
fn differences(root: &Path, schemas: &Path, out: &Path) -> Result<Vec<String>, Failure> {
    let hint = "run `cargo xtask contracts-generate`";
    let files = expected(root, schemas, out)?;
    let mut problems = Vec::new();
    for (path, text) in &files {
        let shown = workspace::show(root, path);
        match fs::read_to_string(path) {
            Ok(actual) if actual == *text => {}
            Ok(_) => problems.push(format!("{shown}: out of date; {hint}")),
            Err(_) => problems.push(format!("{shown}: missing; {hint}")),
        }
    }
    if out.is_dir() {
        for path in stale(out, &files)? {
            let shown = workspace::show(root, &path);
            problems.push(format!("{shown}: generated from no schema; {hint}"));
        }
    }
    Ok(problems)
}

/// The Rust files in `out` that are not among `files`.
fn stale(out: &Path, files: &[(PathBuf, String)]) -> Result<Vec<PathBuf>, Failure> {
    Ok(workspace::sorted_entries(out)?
        .into_iter()
        .filter(|path| path.extension().is_some_and(|extension| extension == "rs"))
        .filter(|path| !files.iter().any(|(file, _)| file == path))
        .collect())
}

/// Returns every file `schemas` generates into `out`, with its formatted text: `mod.rs`,
/// then one `<contract>_v<version>.rs` per contract version.
///
/// # Errors
///
/// Fails if the layout is broken, a schema cannot be read or generated, or `rustfmt` fails.
fn expected(root: &Path, schemas: &Path, out: &Path) -> Result<Vec<(PathBuf, String)>, Failure> {
    let mut modules = Vec::new();
    for version in layout::versions(schemas)? {
        let shown_schema = workspace::show(root, &version.schema);
        let schema = Json::parse(&workspace::read(&version.schema)?)
            .map_err(|failure| Failure::new(format!("{shown_schema}: {failure:?}")))?;
        let items = model::items(&version.contract, &schema)
            .map_err(|message| Failure::new(format!("{shown_schema}#{message}")))?;
        modules.push(Module {
            name: format!("{}_v{}", version.contract, version.version),
            contract: version.contract.clone(),
            version: version.version,
            shown_schema,
            include: relative(out, &version.schema),
            items,
        });
    }
    let mut files = vec![(
        out.join("mod.rs"),
        render::format(
            root,
            &render::registry(&workspace::show(root, schemas), &modules),
        )?,
    )];
    for module in &modules {
        let path = out.join(format!("{}.rs", module.name));
        files.push((path, render::format(root, &render::module(module))?));
    }
    Ok(files)
}

/// The path of `file` relative to the directory `dir`, with `/` between its parts, as
/// `include_str!` takes it on every system (MG-REQ-0189).
fn relative(dir: &Path, file: &Path) -> String {
    let from: Vec<Component<'_>> = dir.components().collect();
    let to: Vec<Component<'_>> = file.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".to_owned(); from.len() - common];
    parts.extend(
        to[common..]
            .iter()
            .map(|part| part.as_os_str().to_string_lossy().into_owned()),
    );
    parts.join("/")
}

